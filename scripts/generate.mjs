#!/usr/bin/env node
// Generate types and endpoint definitions from the PrismCrawl OpenAPI spec.
//
//   node scripts/generate.mjs           regenerate from ./openapi.json
//   node scripts/generate.mjs --fetch   download the latest spec first
//
// Writes src/openapi.gen.ts, src/types.gen.ts, and src/resources.gen.ts. They are
// committed; CI fails if they drift from openapi.json.

import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const root = new URL("../", import.meta.url);
const specUrl = new URL("openapi.json", root);
const SPEC_SOURCE = "https://www.prismcrawl.com/openapi.json";
const HEADER = "// Generated by scripts/generate.mjs from openapi.json. Do not edit by hand.\n";

// Word casing for generated type names.
const WORD_CASE = { duckduckgo: "DuckDuckGo" };
// Extra top-level namespaces that point at an existing one.
const NAMESPACE_ALIASES = { bing: "microsoft" };

const pascal = (value) =>
  value
    .split(/[^0-9A-Za-z]+/)
    .filter(Boolean)
    .map((w) => WORD_CASE[w.toLowerCase()] ?? w[0].toUpperCase() + w.slice(1))
    .join("");

// Attribute names: "app-store" -> "appStore". Brand casing doesn't apply here.
const camel = (value) =>
  value
    .split(/[^0-9A-Za-z]+/)
    .filter(Boolean)
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1)))
    .join("");

const schemaName = (name) => (name.startsWith("Catalog_") ? pascal(name.slice("Catalog_".length)) : name);
const refTarget = (ref) => ref.split("/").pop();

const jsdoc = (text, indent = "") => {
  const clean = text.trim().replaceAll("*/", "*\\/");
  if (!clean) return "";
  const lines = clean.split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l ? " " + l : ""}`).join("\n")}\n${indent} */\n`;
};

if (process.argv.includes("--fetch")) {
  const res = await fetch(SPEC_SOURCE);
  if (!res.ok) throw new Error(`GET ${SPEC_SOURCE} failed: ${res.status}`);
  await writeFile(specUrl, JSON.stringify(await res.json(), null, 2) + "\n");
}

const spec = JSON.parse(await readFile(specUrl, "utf8"));
const schemas = spec.components.schemas;

// Type aliases for every component schema, under readable names.
const names = new Map();
const taken = new Map();
for (const raw of Object.keys(schemas)) {
  const nice = schemaName(raw);
  if (taken.has(nice)) throw new Error(`type name collision: ${raw} and ${taken.get(nice)} -> ${nice}`);
  taken.set(nice, raw);
  names.set(raw, nice);
}

const typeExpr = (schema) => {
  if (schema.$ref) return names.get(refTarget(schema.$ref));
  const alts = schema.oneOf ?? schema.anyOf;
  if (alts) return alts.map(typeExpr).join(" | ");
  throw new Error(`unsupported response schema: ${JSON.stringify(schema).slice(0, 80)}`);
};

// Endpoints: one per POST operation, each paired with a GET history operation.
const endpoints = [];
const extraAliases = [];
for (const [path, item] of Object.entries(spec.paths)) {
  const op = item.post;
  if (!op) continue;
  if (!spec.paths[`${path}/{request_id}`]) throw new Error(`${path} has no history endpoint`);
  const segments = path.split("/").filter(Boolean);
  if (segments[0] !== "v1") throw new Error(`unexpected path ${path}`);
  const attrPath = segments.slice(1).map(camel);

  const request = refTarget(op.requestBody.content["application/json"].schema.$ref);
  const resSchema = op.responses["200"].content["application/json"].schema;
  let response;
  if (resSchema.$ref) {
    response = names.get(refTarget(resSchema.$ref));
  } else {
    response = attrPath.map(pascal).join("") + "Response";
    if (taken.has(response)) throw new Error(`type name collision: ${response}`);
    taken.set(response, path);
    extraAliases.push({ name: response, expr: typeExpr(resSchema), description: `${op.summary} response.` });
  }

  const props = schemas[request].properties ?? {};
  const pagination = "next_page_token" in props ? "token" : "page" in props ? "page" : null;
  endpoints.push({
    attrPath,
    path,
    summary: op.summary ?? "",
    description: op.description ?? schemas[request].description ?? "",
    request: names.get(request),
    response,
    pagination,
  });
}
endpoints.sort((a, b) => a.attrPath.join(".").localeCompare(b.attrPath.join(".")));

// Namespace tree.
const tree = { path: [], children: new Map(), endpoints: new Map() };
for (const ep of endpoints) {
  let node = tree;
  for (const seg of ep.attrPath.slice(0, -1)) {
    if (node.endpoints.has(seg)) throw new Error(`${seg} is both an endpoint and a namespace`);
    if (!node.children.has(seg)) node.children.set(seg, { path: [...node.path, seg], children: new Map(), endpoints: new Map() });
    node = node.children.get(seg);
  }
  const leaf = ep.attrPath.at(-1);
  if (node.children.has(leaf)) throw new Error(`${leaf} is both an endpoint and a namespace`);
  node.endpoints.set(leaf, ep);
}

const nsName = (node) => (node.path.length ? node.path.map(pascal).join("") + "Resource" : "Resources");
const sorted = (map) => [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
const walk = (node) => [...sorted(node.children).flatMap(([, c]) => walk(c)), node];

const endpointType = (ep) =>
  `${ep.pagination ? "PaginatedEndpoint" : "Endpoint"}<T.${ep.request}, T.${ep.response}>`;

const endpointDoc = (ep, indent) =>
  jsdoc(`${ep.summary}: \`POST ${ep.path}\`\n\n${ep.description}`.trim(), indent);

// src/openapi.gen.ts
const ast = await openapiTS(specUrl, { alphabetize: false, defaultNonNullable: false });
await writeFile(new URL("src/openapi.gen.ts", root), HEADER + "/* eslint-disable */\n" + astToString(ast));

// src/types.gen.ts
let types = HEADER + 'import type { components } from "./openapi.gen.js";\n\ntype Schemas = components["schemas"];\n';
// openapi-typescript ignores a top-level `oneOf` that only lists required fields, e.g.
// "exactly one of location or coordinates". Express it as a union so it's enforced.
const exclusiveRequired = (raw) => {
  const alts = schemas[raw].oneOf;
  if (!alts?.length || !alts.every((a) => Object.keys(a).length === 1 && Array.isArray(a.required))) return null;
  const keys = [...new Set(alts.flatMap((a) => a.required))];
  const base = `Schemas["${raw}"]`;
  const variants = alts.map((a) => {
    const fields = keys.map((k) =>
      a.required.includes(k) ? `${k}: NonNullable<${base}["${k}"]>` : `${k}?: never`,
    );
    return `{ ${fields.join("; ")} }`;
  });
  return `Omit<${base}, ${keys.map((k) => `"${k}"`).join(" | ")}> & (${variants.join(" | ")})`;
};

for (const [raw, nice] of names) {
  const expr = exclusiveRequired(raw) ?? `Schemas["${raw}"]`;
  types += "\n" + jsdoc(schemas[raw].description ?? "") + `export type ${nice} = ${expr};\n`;
}
for (const alias of extraAliases) {
  types += "\n" + jsdoc(alias.description) + `export type ${alias.name} = ${alias.expr};\n`;
}
await writeFile(new URL("src/types.gen.ts", root), types);

// src/resources.gen.ts
let res = HEADER;
res += 'import type { Transport } from "./core.js";\n';
res += 'import { createEndpoint, type Endpoint, type PaginatedEndpoint } from "./endpoint.js";\n';
res += 'import type * as T from "./types.gen.js";\n';

for (const node of walk(tree)) {
  const label = node.path.length ? `${node.path.map(pascal).join(" ")} endpoints.` : "Every API namespace.";
  res += `\n/** ${label} */\nexport interface ${nsName(node)} {\n`;
  for (const [name, child] of sorted(node.children)) {
    res += `  readonly ${name}: ${nsName(child)};\n`;
  }
  for (const [name, ep] of sorted(node.endpoints)) {
    res += endpointDoc(ep, "  ") + `  readonly ${name}: ${endpointType(ep)};\n`;
  }
  if (!node.path.length) {
    for (const [alias, target] of Object.entries(NAMESPACE_ALIASES)) {
      res += `  /** Alias of \`${target}\`. */\n  readonly ${alias}: ${nsName(tree.children.get(target))};\n`;
    }
  }
  res += "}\n";
}

const literal = (node, indent) => {
  const inner = indent + "  ";
  const lines = [];
  for (const [name, child] of sorted(node.children)) lines.push(`${inner}${name}: ${literal(child, inner)},`);
  for (const [name, ep] of sorted(node.endpoints)) {
    const pagination = ep.pagination ? `, "${ep.pagination}"` : "";
    lines.push(`${inner}${name}: createEndpoint(transport, "${ep.path}"${pagination}),`);
  }
  return `{\n${lines.join("\n")}\n${indent}}`;
};

res += "\n/** Build the endpoint tree for a client. */\nexport function createResources(transport: Transport): Resources {\n";
for (const [name, child] of sorted(tree.children)) {
  res += `  const ${name}: ${nsName(child)} = ${literal(child, "  ")};\n`;
}
const rootKeys = [...sorted(tree.children).map(([n]) => n), ...Object.entries(NAMESPACE_ALIASES).map(([a, t]) => `${a}: ${t}`)];
res += `  return { ${rootKeys.join(", ")} };\n}\n`;

res += "\n/** Every endpoint, for tests and tooling. */\nexport const ENDPOINTS = [\n";
for (const ep of endpoints) {
  res += `  { path: "${ep.path}", attrPath: ${JSON.stringify(ep.attrPath)}, pagination: ${JSON.stringify(ep.pagination)} },\n`;
}
res += "] as const;\n";
await writeFile(new URL("src/resources.gen.ts", root), res);

console.log(`Generated ${endpoints.length} endpoints and ${names.size + extraAliases.length} types.`);
